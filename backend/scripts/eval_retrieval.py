"""Run the labeled retrieval queries and write evidence/q2/retrieval_report.{md,json}.

Verdict: correct = expected (or accepted alternative) record ranked #1, or a correct refusal for
out-of-scope queries; partially correct = expected record in top 3; incorrect otherwise."""
import json
import statistics
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from app.config import settings  # noqa: E402
from app.retrieval.answer import answer  # noqa: E402
from app.retrieval.index import get_index  # noqa: E402
from app.retrieval.text import terms  # noqa: E402


def _matches(hit: dict, record: dict, spec: dict) -> bool:
    return record["source_id"] == spec["source_id"] and spec["title"].lower() in hit["title"].lower()


def evaluate() -> dict:
    index = get_index()
    queries = json.loads((settings.root / "data" / "eval" / "retrieval_queries.json").read_text(encoding="utf-8"))
    rows = []
    for q in queries:
        res = index.search(q["query"], market=q["market"], top_k=5)
        ans = answer(q["query"], market=q["market"], lang={"IN": "en", "PH": "en", "ID": "id"}[q["market"]], result=res)
        hits = [h.to_dict() for h in res.hits]
        recs = [index.by_id[h["record_id"]] for h in hits]
        specs = ([q["expect"]] + q.get("accept", [])) if q["expect"] else []
        rank = next((i for i, (h, r) in enumerate(zip(hits, recs)) if any(_matches(h, r, s) for s in specs)), None)
        if not specs:
            verdict = "correct" if res.status == "INSUFFICIENT_EVIDENCE" else "incorrect"
        elif res.status != "OK":
            verdict = "incorrect"
        else:
            verdict = "correct" if rank == 0 else "partially correct" if rank is not None and rank < 3 else "incorrect"
        top = hits[0] if hits else None
        shared = sorted(set(terms(q["query"])) & set(terms(top["title"] + " " + top["content"]))) if top else []
        rows.append({
            "id": q["id"], "type": q["type"], "market": q["market"], "query": q["query"],
            "status": res.status, "verdict": verdict, "expected_rank": None if rank is None else rank + 1,
            "top": top, "top3": [{k: h[k] for k in ("record_id", "title", "confidence", "score")} for h in hits[:3]],
            "answer": ans["answer"], "citations": ans["citations"], "shared_terms": shared,
            "latency_ms": res.latency_ms, "note": q.get("note", ""),
        })
    lat = [r["latency_ms"] for r in rows]
    summary = {
        "queries": len(rows),
        "correct": sum(r["verdict"] == "correct" for r in rows),
        "partially_correct": sum(r["verdict"] == "partially correct" for r in rows),
        "incorrect": sum(r["verdict"] == "incorrect" for r in rows),
        "out_of_scope_refusals": f"{sum(r['type'] == 'out_of_scope' and r['status'] != 'OK' for r in rows)}/"
                                 f"{sum(r['type'] == 'out_of_scope' for r in rows)}",
        "latency_ms_p50": round(statistics.median(lat), 2),
        "latency_ms_p95": round(sorted(lat)[max(0, int(len(lat) * 0.95) - 1)], 2),
        "embedder": index.embedder.name, "threshold": settings.retrieval_min_score,
        "kb_version": index.records[0]["kb_version"],
    }
    return {"summary": summary, "rows": rows}


def write_report(result: dict) -> Path:
    out = settings.evidence_dir / "q2"
    out.mkdir(parents=True, exist_ok=True)
    (out / "retrieval_report.json").write_text(json.dumps(result, indent=2, ensure_ascii=False), encoding="utf-8")
    s = result["summary"]
    lines = [
        "# Q2 Retrieval Evaluation", "",
        f"Generated by `python backend/scripts/eval_retrieval.py`. KB version `{s['kb_version']}`, embedder `{s['embedder']}`, "
        f"confidence threshold `{s['threshold']}`.", "",
        f"**{s['correct']} correct, {s['partially_correct']} partially correct, {s['incorrect']} incorrect** out of {s['queries']} queries. "
        f"Out-of-scope refusals: {s['out_of_scope_refusals']}. Search latency P50 {s['latency_ms_p50']} ms, P95 {s['latency_ms_p95']} ms.", "",
        "| ID | Type | Query | Retrieved record (top 1) | Confidence | Verdict |", "|---|---|---|---|---|---|",
    ]
    for r in result["rows"]:
        top = r["top"]
        rec = f"`{top['record_id']}` {top['title']}" if top and r["status"] == "OK" else "INSUFFICIENT_EVIDENCE"
        conf = f"{top['confidence']:.2f}" if top else "-"
        lines.append(f"| {r['id']} | {r['type']} | {r['query']} | {rec} | {conf} | {r['verdict']} |")
    lines += ["", "## Per-query detail", ""]
    for r in result["rows"]:
        top = r["top"]
        lines.append(f"### {r['id']} - {r['query']}")
        lines.append(f"- **Verdict:** {r['verdict']} (expected record rank: {r['expected_rank'] or 'n/a'})")
        if r["status"] == "OK" and top:
            lines.append(f"- **Retrieved chunk:** {top['content']}")
            lines.append(f"- **Source reference:** {top['citation']}")
            lines.append(f"- **Relevance:** shares query terms {r['shared_terms'] or '(semantic match only)'}; "
                         f"BM25 {top['bm25']}, dense cosine {top['dense']}, term coverage {top['term_coverage']}.")
        else:
            best = top["confidence"] if top else 0
            lines.append(f"- **Retrieved chunk:** none returned; best candidate confidence {best:.2f} is below threshold.")
        lines.append(f"- **Bot answer:** {r['answer']}")
        if r["note"]:
            lines.append(f"- **Note:** {r['note']}")
        lines.append("")
    path = out / "retrieval_report.md"
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


if __name__ == "__main__":
    res = evaluate()
    print(json.dumps(res["summary"], indent=2))
    for r in res["rows"]:
        t = r["top3"]
        print(r["id"], r["verdict"], r["status"], [(x["title"][:30], round(x["confidence"], 2)) for x in t])
    print("report:", write_report(res))
